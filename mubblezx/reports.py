"""Report generators for mubbleZX scan results."""

import csv
import json
from datetime import datetime


def save_json(scan_result, path=None):
    if not path:
        path = f"mubbleZX_{scan_result.scan_id}.json"
    with open(path, "w") as f:
        json.dump(scan_result.to_dict(), f, indent=2)
    return path


def save_csv(scan_result, path=None):
    if not path:
        path = f"mubbleZX_{scan_result.scan_id}.csv"
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["IP", "MAC", "Vendor", "Hostname", "Type", "OS", "Risk", "Open Ports", "Services"])
        for d in scan_result.devices:
            ports = ", ".join(str(p["port"]) for p in d.get("open_ports", []))
            services = ", ".join(p.get("service", "") for p in d.get("open_ports", []))
            writer.writerow([
                d["ip"], d.get("mac", ""), d.get("vendor", ""),
                d.get("hostname", ""), d.get("device_type", ""),
                d.get("os", ""), d.get("risk_level", ""),
                ports, services,
            ])
    return path


def save_html(scan_result, path=None):
    if not path:
        path = f"mubbleZX_{scan_result.scan_id}.html"

    devices = scan_result.devices
    rows = ""
    for d in devices:
        port_count = len(d.get("open_ports", []))
        risk = d.get("risk_level", "UNKNOWN")
        risk_color = {"CRITICAL": "#e74c3c", "HIGH": "#e67e22", "MEDIUM": "#f1c40f", "LOW": "#2ecc71"}.get(risk, "#95a5a6")
        rows += f"""<tr>
            <td>{d['ip']}</td>
            <td>{d.get('mac', 'N/A')}</td>
            <td>{d.get('vendor', 'Unknown')}</td>
            <td>{d.get('device_type', 'Unknown')}</td>
            <td>{d.get('os', 'N/A')}</td>
            <td style="color:{risk_color};font-weight:bold">{risk}</td>
            <td>{port_count}</td>
        </tr>\n"""

    html = f"""<!DOCTYPE html>
<html><head><title>mubbleZX Scan Report</title>
<style>
body {{ font-family: monospace; background: #1a1a2e; color: #eee; margin: 20px; }}
h1 {{ color: #0ff; }}
table {{ width: 100%; border-collapse: collapse; margin-top: 20px; }}
th {{ background: #16213e; color: #0ff; padding: 10px; text-align: left; }}
td {{ padding: 8px; border-bottom: 1px solid #333; }}
tr:hover {{ background: #16213e; }}
.meta {{ color: #888; margin-bottom: 20px; }}
</style></head><body>
<h1>mubbleZX Scan Report</h1>
<div class="meta">
    Network: {scan_result.network} |
    Interface: {scan_result.interface_label or 'N/A'} |
    Devices: {len(devices)} |
    Time: {scan_result.timestamp}
</div>
<table>
<tr><th>IP</th><th>MAC</th><th>Vendor</th><th>Type</th><th>OS</th><th>Risk</th><th>Ports</th></tr>
{rows}
</table>
<footer style="margin-top:40px;color:#555;text-align:center">Generated by mubbleZX v13</footer>
</body></html>"""

    with open(path, "w") as f:
        f.write(html)
    return path
